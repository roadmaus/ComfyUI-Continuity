#!/usr/bin/env python3
"""Vendor the ComfyUI-Krea2Edit nodes into the pack.

Upstream — <https://github.com/lbouaraba/comfyui-krea2edit>, Apache-2.0 — is
the node pack the Krea 2 Identity Edit and General Edit LoRAs were trained to
be read through: a DIFFUSION_MODEL wrapper that lays the references into the
token sequence as clean frames, and an image-grounded Qwen3-VL encode. The
whole of it is one module, `__init__.py`, and it is copied whole as
`krea2edit/nodes.py`. Its two node classes are upstream's product and are
never registered here; `creator/krea2edit/__init__.py` says why this is copied
rather than installed, and is written by hand — this script never touches it.
The example workflow and upstream's tests stay upstream.

**Local deltas are re-applied, not re-invented**, on the h3lora rule: edits to
the copy are held as a patch (`tools/krea2edit.patch`, regenerated by `--save`)
and applied after the copy. A hunk that no longer applies is a hard error.
There is no patch file until there is a delta to hold.

Re-syncing:

    git clone https://github.com/lbouaraba/comfyui-krea2edit /tmp/krea2edit
    git -C /tmp/krea2edit checkout <commit>
    python3 tools/vendor_krea2edit.py /tmp/krea2edit
    COMFYUI_PATH=~/ComfyUI <comfy-venv>/bin/python3 tests/test_krea2edit_vendor.py

    python3 tools/vendor_krea2edit.py --save     # local edits -> tools/krea2edit.patch

The revision is stamped into `__init__.py`'s docstring and into its `REVISION`
constant, and the upstream version into `VERSION`.
"""

import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "creator", "krea2edit")
PATCH = os.path.join(ROOT, "tools", "krea2edit.patch")
HEADER = os.path.join(OUT, "__init__.py")

UPSTREAM = "lbouaraba/comfyui-krea2edit"

# Upstream's file -> where it lands here. The package root is the module; here
# it is a module of a package whose `__init__` is ours.
FILES = (("__init__.py", "nodes.py"), ("LICENSE", "LICENSE"))


def git(clone, *args):
    try:
        out = subprocess.run(["git", "-C", clone, *args],
                             capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"


def version(clone):
    path = os.path.join(clone, "pyproject.toml")
    try:
        with open(path, encoding="utf-8") as handle:
            found = re.search(r'^version\s*=\s*"([^"]+)"', handle.read(), re.M)
    except OSError:
        found = None
    return found.group(1) if found else "unknown"


def save_patch():
    diff = subprocess.run(
        ["git", "-C", ROOT, "diff", "--", "creator/krea2edit"],
        capture_output=True, text=True, check=True).stdout
    if not diff.strip():
        sys.exit("nothing to save: creator/krea2edit/ has no uncommitted changes")
    with open(PATCH, "w", encoding="utf-8") as handle:
        handle.write(diff)
    print(f"wrote {os.path.relpath(PATCH, ROOT)} ({len(diff.splitlines())} lines)")


def stamp(short, full, when, release):
    """Rewrite the revision line and the constants in the hand-written init."""
    with open(HEADER, "r", encoding="utf-8") as handle:
        text = handle.read()
    text, a = re.subn(r"revision `[^`]+` \([^)]*\)", f"revision `{short}` ({when})", text, count=1)
    text, b = re.subn(r'^REVISION = "[0-9a-f]*"$', f'REVISION = "{full}"', text, count=1, flags=re.M)
    text, c = re.subn(r'^VERSION = "[^"]*"$', f'VERSION = "{release}"', text, count=1, flags=re.M)
    if not (a and b and c):
        sys.exit(f"{HEADER} no longer carries a revision line, REVISION and VERSION to stamp")
    with open(HEADER, "w", encoding="utf-8") as handle:
        handle.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("clone", nargs="?", help="path to a clone of " + UPSTREAM)
    parser.add_argument("--save", action="store_true",
                        help="write the current local edits to tools/krea2edit.patch")
    args = parser.parse_args()

    if args.save:
        save_patch()
        return
    if not args.clone:
        parser.error("a path to an upstream clone is required")

    os.makedirs(OUT, exist_ok=True)
    for src_name, out_name in FILES:
        src = os.path.join(args.clone, src_name)
        if not os.path.isfile(src):
            sys.exit(f"upstream no longer ships {src_name} — check what replaced it")
        with open(src, "rb") as handle:
            body = handle.read()
        with open(os.path.join(OUT, out_name), "wb") as handle:
            handle.write(body)
        print(f"copied {src_name} -> krea2edit/{out_name}")

    if os.path.isfile(PATCH):
        result = subprocess.run(["git", "-C", ROOT, "apply", "--verbose", PATCH],
                                capture_output=True, text=True)
        if result.returncode:
            sys.exit(
                f"{os.path.relpath(PATCH, ROOT)} no longer applies:\n{result.stderr}\n"
                "Upstream has changed the code a local fix sits on. Read the "
                "hunks — most likely upstream has made the fix themselves and "
                "the local one should be dropped from the patch.")
        print(f"applied {os.path.relpath(PATCH, ROOT)}")

    short = git(args.clone, "rev-parse", "--short", "HEAD")
    full = git(args.clone, "rev-parse", "HEAD")
    when = git(args.clone, "log", "-1", "--format=%cs")
    release = version(args.clone)
    stamp(short, full, when, release)
    print(f"stamped {UPSTREAM} {release} @ {short} ({when})")


if __name__ == "__main__":
    main()
