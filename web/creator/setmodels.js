// What a piece of a set can look like: a chair, a car, a tree, at two levels of
// detail above the box it always was.
//
// Nothing is loaded. Every model is a handful of convex parts in a unit box,
// x across, y up and z to the front, and the box is the piece's own: a piece
// keeps its width, height and depth whatever it looks like, so changing a model
// or its detail moves and resizes nothing. Rocks and bushes reach below it, into the floor. A guide is read for masses and
// outlines, so a part is there only if it changes one of those.

// ---- parts ---------------------------------------------------------------------

/** A box, by its six bounds. */
const b = (x0, x1, y0, y1, z0, z1) => ({ kind: "box", at: [x0, x1, y0, y1, z0, z1] });

/** A round, standing on axis `axis`: its far end is `top` of its near end's
 *  width, so 0 is a cone. */
const c = (x0, x1, y0, y1, z0, z1, { axis = "y", sides = 10, top = 1 } = {}) =>
  ({ kind: "round", at: [x0, x1, y0, y1, z0, z1], axis, sides, top });

/** A side outline, as [z, y] corners of a convex shape, run from `x0` to `x1`. */
const p = (x0, x1, outline) => ({ kind: "prism", x0, x1, outline });

/** A lump: a rough ball in the bounds. */
const s = (x0, x1, y0, y1, z0, z1) => ({ kind: "lump", at: [x0, x1, y0, y1, z0, z1] });

/** Four legs of thickness `w` and `d`, from the floor to `top`. */
const legs = (top, w, d = w) => [b(0, w, 0, top, 0, d), b(1 - w, 1, 0, top, 0, d), b(0, w, 0, top, 1 - d, 1), b(1 - w, 1, 0, top, 1 - d, 1)];

/** Four wheels: `r` of the length and `tall` of the height, `zs` along it. */
const wheels = (zs, r, tall, wide, sides = 10) => zs.flatMap((z) => [
  c(0, wide, 0, tall, z - r, z + r, { axis: "x", sides }), c(1 - wide, 1, 0, tall, z - r, z + r, { axis: "x", sides })]);

const steps = (n) => Array.from({ length: n }, (_, k) => b(0, 1, 0, (k + 1) / n, 1 - (k + 1) / n, 1 - k / n));
const rungs = (n, y0, y1, x0, x1, z0, z1) => Array.from({ length: n }, (_, k) => {
  const y = y0 + ((y1 - y0) * k) / Math.max(1, n - 1);
  return b(x0, x1, y, y + 0.02, z0, z1);
});
const slats = (n, wide, y0, y1, z0, z1) => Array.from({ length: n }, (_, k) => {
  const x = ((1 - wide) * k) / (n - 1);
  return b(x, x + wide, y0, y1, z0, z1);
});

