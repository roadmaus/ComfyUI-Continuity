export const MODELS = new Map(MODEL_GROUPS.flatMap((group) => group.models).map((model) => [model.id, model]));

// ---- parts, as triangles -----------------------------------------------------------

const CORNERS = [[0, 2, 4], [1, 2, 4], [1, 3, 4], [0, 3, 4], [0, 2, 5], [1, 2, 5], [1, 3, 5], [0, 3, 5]];
const QUADS = [[0, 1, 2, 3], [4, 5, 6, 7], [0, 1, 5, 4], [3, 2, 6, 7], [0, 3, 7, 4], [1, 2, 6, 5]];

/** A part's corners and its faces, each a list of corners. Every part is convex. */
function hull(part) {
  if (part.kind === "box") return { points: CORNERS.map((corner) => corner.map((k) => part.at[k])), faces: QUADS };
  if (part.kind === "prism") {
    const n = part.outline.length;
    return {
      points: [part.x0, part.x1].flatMap((x) => part.outline.map(([z, y]) => [x, y, z])),
      faces: [Array.from({ length: n }, (_, k) => k), Array.from({ length: n }, (_, k) => n + k),
        ...Array.from({ length: n }, (_, k) => [k, (k + 1) % n, n + ((k + 1) % n), n + k])],
    };
  }
  const [x0, x1, y0, y1, z0, z1] = part.at;
  const lo = [x0, y0, z0], hi = [x1, y1, z1];
  const mid = lo.map((v, k) => (v + hi[k]) / 2), half = lo.map((v, k) => (hi[k] - v) / 2);
  if (part.kind === "round") {
    const along = "xyz".indexOf(part.axis), u = (along + 1) % 3, v = (along + 2) % 3;
    const n = part.sides, points = [];
    for (const [end, wide] of [[lo[along], 1], [hi[along], part.top]]) {
      for (let k = 0; k < n; k++) {
        const angle = ((k + 0.5) / n) * 2 * Math.PI, point = [0, 0, 0];
        point[along] = end;
        point[u] = mid[u] + half[u] * wide * Math.cos(angle);
        point[v] = mid[v] + half[v] * wide * Math.sin(angle);
        points.push(point);
      }
    }
    return { points, faces: [Array.from({ length: n }, (_, k) => k), Array.from({ length: n }, (_, k) => n + k),
      ...Array.from({ length: n }, (_, k) => [k, (k + 1) % n, n + ((k + 1) % n), n + k])] };
  }
  // A lump: rings of a rough ball.
  const n = 7, rings = [0.5, 1, 1.5, 2, 2.5].map((ring) => (ring / 3) * Math.PI);
  const points = [];
  for (const [r, fall] of rings.entries()) {
    for (let k = 0; k < n; k++) {
      const angle = ((k + (r % 2) / 2) / n) * 2 * Math.PI;
      points.push([mid[0] + half[0] * Math.sin(fall) * Math.cos(angle), mid[1] - half[1] * Math.cos(fall) / Math.cos(rings[0]), mid[2] + half[2] * Math.sin(fall) * Math.sin(angle)]);
    }
  }
  const faces = [Array.from({ length: n }, (_, k) => k), Array.from({ length: n }, (_, k) => (rings.length - 1) * n + k)];
  for (let r = 0; r < rings.length - 1; r++) {
    for (let k = 0; k < n; k++) {
      const a = r * n + k, d = r * n + ((k + 1) % n), e = a + n, f = d + n;
      if (r % 2) faces.push([a, d, f], [a, f, e]);
      else faces.push([a, d, e], [d, f, e]);
    }
  }
  return { points, faces };
}

const built = new Map();

/**
 * A model's triangles in a unit box about the origin (-1 to 1 each way), wound
 * as the renderer's own boxes are, each with the part it belongs to (from 1).
 * Null for a box: no model, one nobody knows, or a piece shown as a block.
 */
export function modelTriangles(piece) {
  const model = MODELS.get(piece.model);
  if (!model || piece.detail === "block") return null;
  const level = piece.detail === "detailed" ? "detailed" : "shape";
  const key = `${model.id}:${level}`;
  if (built.has(key)) return built.get(key);
  const out = [];
  model[level].forEach((part, index) => {
    const { points, faces } = hull(part);
    const unit = points.map((point) => point.map((value) => value * 2 - 1));
    const inside = [0, 1, 2].map((k) => unit.reduce((sum, point) => sum + point[k], 0) / unit.length);
    for (const face of faces) {
      for (let k = 1; k + 1 < face.length; k++) {
        let [p0, p1, p2] = [unit[face[0]], unit[face[k]], unit[face[k + 1]]];
        const e = p1.map((v, n) => v - p0[n]), f = p2.map((v, n) => v - p0[n]);
        const normal = [e[1] * f[2] - e[2] * f[1], e[2] * f[0] - e[0] * f[2], e[0] * f[1] - e[1] * f[0]];
        if (Math.hypot(...normal) < 1e-9) continue;
        if (normal.reduce((sum, v, n) => sum + v * (p0[n] - inside[n]), 0) > 0) [p1, p2] = [p2, p1];
        out.push({ part: index + 1, v: [p0, p1, p2] });
      }
    }
  });
  built.set(key, out);
  return out;
}
